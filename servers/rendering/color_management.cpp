#include "color_management.h"

void ColorManagement::configure(bool p_enabled, const Basis &p_rec709_to_working, const Basis &p_working_to_rec709) {
	// An identity matrix means the working space already is linear Rec.709, so
	// there is nothing to convert and the cheaper disabled path is equivalent.
	enabled = p_enabled && !p_rec709_to_working.is_equal_approx(Basis());
	rec709_to_working = enabled ? p_rec709_to_working : Basis();
	working_to_rec709 = enabled ? p_working_to_rec709 : Basis();
}
