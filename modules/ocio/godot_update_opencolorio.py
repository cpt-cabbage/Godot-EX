#!/usr/bin/env python3
"""Vendor OpenColorIO and its dependencies into Godot's thirdparty/ directory.

Godot does not run CMake, so this script performs the work CMake would normally
do at configure time:

  * copies the subset of each upstream tree that Godot actually compiles,
  * writes the headers CMake would have generated from ``*.h.in`` templates
    (``OpenColorABI.h``, ``CPUInfoConfig.h``, ``ImathConfig.h``,
    ``expat_config.h``),
  * hex-encodes OCIO's built-in ACES configs into the ``CG.cpp`` / ``Studio.cpp``
    data files that ``builtinconfigs/*Config.cpp`` include,
  * replaces ``OCIOZArchive.cpp`` with a stub so that minizip-ng is not needed
    (Godot does not support ``.ocioz`` archived configs).

Usage:
    python modules/ocio/godot_update_opencolorio.py            # download + vendor
    python modules/ocio/godot_update_opencolorio.py --src DIR  # use extracted trees in DIR

Run from anywhere; paths are resolved relative to this file.
"""

import argparse
import os
import shutil
import subprocess
import sys
import tarfile
import tempfile

# Pinned upstream versions. Keep in sync with thirdparty/README.md.
OCIO_VERSION = "2.4.2"
IMATH_VERSION = "3.1.12"
YAML_CPP_VERSION = "0.8.0"
PYSTRING_VERSION = "1.1.4"
EXPAT_VERSION = "2.6.4"

DOWNLOADS = {
    "OpenColorIO-%s" % OCIO_VERSION: "https://github.com/AcademySoftwareFoundation/OpenColorIO/archive/refs/tags/v%s.tar.gz"
    % OCIO_VERSION,
    "Imath-%s" % IMATH_VERSION: "https://github.com/AcademySoftwareFoundation/Imath/archive/refs/tags/v%s.tar.gz"
    % IMATH_VERSION,
    "yaml-cpp-%s" % YAML_CPP_VERSION: "https://github.com/jbeder/yaml-cpp/archive/refs/tags/%s.tar.gz" % YAML_CPP_VERSION,
    "pystring-%s" % PYSTRING_VERSION: "https://github.com/imageworks/pystring/archive/refs/tags/v%s.tar.gz"
    % PYSTRING_VERSION,
    "expat-%s" % EXPAT_VERSION: "https://github.com/libexpat/libexpat/releases/download/R_%s/expat-%s.tar.gz"
    % (EXPAT_VERSION.replace(".", "_"), EXPAT_VERSION),
}

MODULE_DIR = os.path.dirname(os.path.abspath(__file__))
GODOT_ROOT = os.path.normpath(os.path.join(MODULE_DIR, "..", ".."))
THIRDPARTY = os.path.join(GODOT_ROOT, "thirdparty")


def rmtree(path):
    if os.path.isdir(path):
        shutil.rmtree(path)


def copy_tree(src, dst, skip_dirs=(), skip_names=(), suffixes=None):
    """Copy src into dst, filtering by directory name, file name and suffix."""
    for root, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in skip_dirs]
        for name in files:
            if name in skip_names:
                continue
            if suffixes is not None and not name.endswith(suffixes):
                continue
            rel = os.path.relpath(os.path.join(root, name), src)
            out = os.path.join(dst, rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            shutil.copyfile(os.path.join(root, name), out)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def download_and_extract(dest):
    """Fetch every pinned tarball into `dest` and extract it there."""
    for name, url in DOWNLOADS.items():
        if os.path.isdir(os.path.join(dest, name)):
            print("  %s already present, skipping download" % name)
            continue
        archive = os.path.join(dest, name + ".tar.gz")
        print("  fetching %s" % url)
        subprocess.run(["curl", "-sSL", "--fail", "--max-time", "300", "-o", archive, url], check=True)
        with tarfile.open(archive) as tar:
            tar.extractall(dest)
    return dest


# ---------------------------------------------------------------------------
# Generated headers (the work CMake's configure_file() would do)
# ---------------------------------------------------------------------------

GENERATED_BANNER = """// Generated by modules/ocio/godot_update_opencolorio.py from {template}.
// Do not edit by hand; edit the script and re-run it instead.
"""


def configure_file(template_path, out_path, variables, options):
    """Do what CMake's configure_file() would: expand @VAR@ and #cmakedefine.

    `variables` maps @NAME@ placeholders to their replacement text.
    `options` maps #cmakedefine / #cmakedefine01 names to a truthy value.
    """
    out_lines = []
    with open(template_path, encoding="utf-8") as f:
        for line in f.read().splitlines():
            stripped = line.strip()
            if stripped.startswith("#cmakedefine01 "):
                name = stripped.split(None, 1)[1].strip()
                if name not in options:
                    sys.exit("error: %s: no value given for #cmakedefine01 %s" % (template_path, name))
                line = "#define %s %d" % (name, 1 if options[name] else 0)
            elif stripped.startswith("#cmakedefine "):
                name = stripped.split(None, 1)[1].strip()
                if name not in options:
                    sys.exit("error: %s: no value given for #cmakedefine %s" % (template_path, name))
                line = "#define %s 1" % name if options[name] else "/* #undef %s */" % name
            for key, value in variables.items():
                line = line.replace("@%s@" % key, str(value))
            out_lines.append(line)

    text = "\n".join(out_lines) + "\n"
    if "@" in text and any("@" in line and line.count("@") >= 2 for line in out_lines):
        leftover = [line for line in out_lines if line.count("@") >= 2]
        sys.exit("error: unresolved placeholders in %s:\n  %s" % (template_path, "\n  ".join(leftover[:5])))

    banner = GENERATED_BANNER.format(template=os.path.basename(template_path))
    write(out_path, banner + text)

