def hex_encode_config(path):
    """Render a .ocio file as the comma-separated 0xNN list CMake would emit."""
    with open(path, "rb") as f:
        data = f.read()
    return ",".join("0x%02x" % b for b in data) + ",0x00"


def generate_builtin_configs(ocio_src, out_dir):
    """Write generated_include/CG.cpp and Studio.cpp from the .ocio configs."""
    template_dir = os.path.join(ocio_src, "src", "OpenColorIO", "builtinconfigs")
    configs_dir = os.path.join(template_dir, "configs")
    for template_name in sorted(os.listdir(template_dir)):
        if not template_name.endswith(".cpp.in"):
            continue
        with open(os.path.join(template_dir, template_name), encoding="utf-8") as f:
            text = f.read()
        for config_name in sorted(os.listdir(configs_dir)):
            if not config_name.endswith(".ocio"):
                continue
            stem = config_name[: -len(".ocio")]
            placeholder = "@%s@" % stem
            if placeholder in text:
                text = text.replace(placeholder, hex_encode_config(os.path.join(configs_dir, config_name)))
        if "@" in text.split("constexpr", 1)[-1]:
            sys.exit("error: unresolved placeholder left in %s" % template_name)
        write(os.path.join(out_dir, template_name[: -len(".in")]), text)
        print("    generated %s" % template_name[: -len(".in")])


