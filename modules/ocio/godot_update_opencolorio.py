def vendor_opencolorio(src):
    dst = os.path.join(THIRDPARTY, "opencolorio")
    rmtree(dst)
    print("  opencolorio ->", os.path.relpath(dst, GODOT_ROOT))

    copy_tree(
        os.path.join(src, "include", "OpenColorIO"),
        os.path.join(dst, "include", "OpenColorIO"),
        suffixes=(".h",),
    )
    copy_tree(
        os.path.join(src, "src", "OpenColorIO"),
        os.path.join(dst, "src", "OpenColorIO"),
        skip_dirs={"res", "configs"},
        skip_names={"CMakeLists.txt"},
        suffixes=(".h", ".cpp"),
    )
    # OCIO's core includes these two headers from src/utils via "utils/...".
    copy_tree(os.path.join(src, "src", "utils"), os.path.join(dst, "src", "utils"), suffixes=(".h",))

    # Header-only libraries that upstream bundles under ext/ and exposes as
    # CMake INTERFACE targets: xxHash (HashUtils.cpp) and a trimmed copy of
    # SampleICC (fileformats/FileFormatICC.cpp).
    for ext_name in ("xxHash", "sampleicc"):
        copy_tree(
            os.path.join(src, "ext", ext_name, "src", "include"),
            os.path.join(dst, "ext", ext_name, "include"),
            suffixes=(".h", ".hpp"),
        )

    major, minor, patch = OCIO_VERSION.split(".")
    configure_file(
        os.path.join(src, "include", "OpenColorIO", "OpenColorABI.h.in"),
        os.path.join(dst, "include", "OpenColorIO", "OpenColorABI.h"),
        variables={
            "OCIO_NAMESPACE": "OpenColorIO_v%s_%s" % (major, minor),
            "OpenColorIO_VERSION": OCIO_VERSION,
            "OpenColorIO_VERSION_RELEASE_TYPE": "",
            "OpenColorIO_VERSION_MAJOR": major,
            "OpenColorIO_VERSION_MINOR": minor,
            "OpenColorIO_VERSION_PATCH": patch,
        },
        options={},
    )
    write(os.path.join(dst, "src", "OpenColorIO", "CPUInfoConfig.h"), CPUINFO_CONFIG_H)
    write(os.path.join(dst, "src", "OpenColorIO", "OCIOZArchive.cpp"), OCIOZ_ARCHIVE_STUB)
    generate_builtin_configs(src, os.path.join(dst, "generated_include"))

    shutil.copyfile(os.path.join(src, "LICENSE"), os.path.join(dst, "LICENSE"))
    shutil.copyfile(os.path.join(src, "THIRD-PARTY.md"), os.path.join(dst, "THIRD-PARTY.md"))


def vendor_imath(src):
    dst = os.path.join(THIRDPARTY, "imath")
    rmtree(dst)
    print("  imath ->", os.path.relpath(dst, GODOT_ROOT))

    # OCIO only needs the half type, not the rest of Imath.
    needed = [
        "half.h",
        "half.cpp",
        "halfLimits.h",
        "ImathExport.h",
        "ImathNamespace.h",
        "ImathPlatform.h",
    ]
    for name in needed:
        os.makedirs(os.path.join(dst, "Imath"), exist_ok=True)
        shutil.copyfile(os.path.join(src, "src", "Imath", name), os.path.join(dst, "Imath", name))

    major, minor, patch = IMATH_VERSION.split(".")
    configure_file(
        os.path.join(src, "config", "ImathConfig.h.in"),
        os.path.join(dst, "Imath", "ImathConfig.h"),
        variables={
            "IMATH_NAMESPACE_CUSTOM": "0",
            "IMATH_NAMESPACE": "Imath",
            "IMATH_INTERNAL_NAMESPACE": "Imath_%s_%s" % (major, minor),
            "IMATH_VERSION": IMATH_VERSION,
            "IMATH_PACKAGE_NAME": "Imath %s" % IMATH_VERSION,
            "Imath_VERSION_MAJOR": major,
            "Imath_VERSION_MINOR": minor,
            "Imath_VERSION_PATCH": patch,
            "IMATH_VERSION_RELEASE_TYPE": "",
            "IMATH_LIB_VERSION": "%s.%s.%s" % (major, minor, patch),
        },
        options={
            # Godot omits the 128 KB half-to-float table; half conversion uses
            # the bit-shift algorithm instead (IMATH_HALF_NO_LOOKUP_TABLE).
            "IMATH_HALF_USE_LOOKUP_TABLE": False,
            "IMATH_HAVE_LARGE_STACK": False,
            "IMATH_USE_NOEXCEPT": True,
            # Built statically into the engine; nothing crosses a library boundary.
            "IMATH_ENABLE_API_VISIBILITY": False,
        },
    )
    shutil.copyfile(os.path.join(src, "LICENSE.md"), os.path.join(dst, "LICENSE.md"))


def vendor_yaml_cpp(src):
    dst = os.path.join(THIRDPARTY, "yaml-cpp")
    rmtree(dst)
    print("  yaml-cpp ->", os.path.relpath(dst, GODOT_ROOT))

    copy_tree(os.path.join(src, "include"), os.path.join(dst, "include"), suffixes=(".h",))
    copy_tree(
        os.path.join(src, "src"),
        os.path.join(dst, "src"),
        skip_dirs={"contrib"},
        suffixes=(".h", ".cpp"),
    )
    shutil.copyfile(os.path.join(src, "LICENSE"), os.path.join(dst, "LICENSE"))


def vendor_pystring(src):
    dst = os.path.join(THIRDPARTY, "pystring")
    rmtree(dst)
    print("  pystring ->", os.path.relpath(dst, GODOT_ROOT))
    os.makedirs(dst, exist_ok=True)
    for name in ("pystring.h", "pystring.cpp", "LICENSE"):
        shutil.copyfile(os.path.join(src, name), os.path.join(dst, name))


def vendor_expat(src):
    dst = os.path.join(THIRDPARTY, "expat")
    rmtree(dst)
    print("  expat ->", os.path.relpath(dst, GODOT_ROOT))

    lib_src = os.path.join(src, "lib")
    os.makedirs(os.path.join(dst, "lib"), exist_ok=True)
    for name in sorted(os.listdir(lib_src)):
        if name.endswith((".c", ".h")):
            shutil.copyfile(os.path.join(lib_src, name), os.path.join(dst, "lib", name))

    write(os.path.join(dst, "lib", "expat_config.h"), EXPAT_CONFIG_H.format(version=EXPAT_VERSION))
    shutil.copyfile(os.path.join(src, "COPYING"), os.path.join(dst, "COPYING"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", help="directory holding the already-extracted upstream trees")
    args = parser.parse_args()

    if args.src:
        source_dir = os.path.abspath(args.src)
        download_and_extract(source_dir)
        run(source_dir)
    else:
        with tempfile.TemporaryDirectory(prefix="ocio-vendor-") as tmp:
            download_and_extract(tmp)
            run(tmp)


def run(source_dir):
    print("Vendoring into", THIRDPARTY)
    vendor_opencolorio(os.path.join(source_dir, "OpenColorIO-%s" % OCIO_VERSION))
    vendor_imath(os.path.join(source_dir, "Imath-%s" % IMATH_VERSION))
    vendor_yaml_cpp(os.path.join(source_dir, "yaml-cpp-%s" % YAML_CPP_VERSION))
    vendor_pystring(os.path.join(source_dir, "pystring-%s" % PYSTRING_VERSION))
    vendor_expat(os.path.join(source_dir, "expat-%s" % EXPAT_VERSION))
    print("Done. Remember to update thirdparty/README.md and COPYRIGHT.txt if versions changed.")


if __name__ == "__main__":
    main()
